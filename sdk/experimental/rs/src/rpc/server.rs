//! The RPC server: Connect, gRPC and gRPC-Web on one port, HTTP/1.1 and
//! h2c, as a `serve::Service` (go: `rpc.Server` + `ListenAndServe`).

use std::net::SocketAddr;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};

use axum::body::Body;
use axum::extract::Request;
use axum::http::{header, HeaderValue, Response, StatusCode};
use axum::middleware::Next;
use connectrpc::{ConnectRpcService, Limits, Router as ConnectRouter};
use tower_http::catch_panic::CatchPanicLayer;
use tower_http::limit::RequestBodyLimitLayer;

use super::interceptor::{Adapter, Interceptor};
use crate::serve::{CancelToken, ReadySignal, ServeFuture, Service};

/// The service name the server registers as.
pub const SERVICE_NAME: &str = "rpc";

/// Default bound on a request body: connectrpc's own default.
pub const DEFAULT_MAX_BODY_BYTES: usize = 4 * 1024 * 1024;

/// Something that serves procedures: kit's [`EntityRpc`](super::EntityRpc),
/// or any stub generated for a tool's own proto.
pub trait RpcService: Send + Sync + 'static {
    /// Add this service's procedures to `mount`.
    fn mount(self: Arc<Self>, mount: &mut Mount);
}

/// Where services register. Opaque: it wraps the connectrpc router, which
/// no kit signature names beyond [`Mount::generated`].
pub struct Mount {
    router: Option<ConnectRouter>,
}

impl Mount {
    /// Register a service from stubs generated by `protoc-gen-connect-rust`
    /// (the generated `FooServiceExt` types). This is the one seam where
    /// generated code, which is connectrpc-typed by construction, meets
    /// the server; kit's own services go through [`RpcService`].
    pub fn generated<S: ?Sized, Marker>(&mut self, service: Arc<S>)
    where
        Arc<S>: connectrpc::ServiceRegister<Marker>,
    {
        let router = self.router.take().expect("mount router present");
        self.router = Some(router.add_service(service));
    }
}

type Registrar = Arc<dyn Fn(&mut Mount) + Send + Sync>;
type PanicHook = Arc<dyn Fn(&str) + Send + Sync>;

/// Configures an [`RpcServer`].
pub struct RpcServerBuilder {
    addr: String,
    services: Vec<Registrar>,
    interceptors: Vec<Arc<dyn Interceptor>>,
    max_body_bytes: usize,
    on_panic: Option<PanicHook>,
}

impl RpcServerBuilder {
    /// Serve on `addr` (`127.0.0.1:0` picks a port; [`Service::addr`]
    /// reports it once ready).
    pub fn new(addr: impl Into<String>) -> Self {
        Self {
            addr: addr.into(),
            services: Vec::new(),
            interceptors: Vec::new(),
            max_body_bytes: DEFAULT_MAX_BODY_BYTES,
            on_panic: None,
        }
    }

    /// Mount a service.
    pub fn service<S: RpcService>(mut self, svc: S) -> Self {
        let svc = Arc::new(svc);
        self.services
            .push(Arc::new(move |m: &mut Mount| svc.clone().mount(m)));
        self
    }

    /// Add an interceptor, applied to every procedure of every mounted
    /// service. The first added runs first.
    pub fn interceptor(mut self, i: impl Interceptor) -> Self {
        self.interceptors.push(Arc::new(i));
        self
    }

    /// Bound a request body (the whole stream for a streaming call).
    pub fn max_body_bytes(mut self, n: usize) -> Self {
        self.max_body_bytes = n;
        self
    }

    /// Called with the panic message when a handler panics. The caller
    /// gets `internal` either way, without the detail.
    pub fn on_panic<F>(mut self, f: F) -> Self
    where
        F: Fn(&str) + Send + Sync + 'static,
    {
        self.on_panic = Some(Arc::new(f));
        self
    }

    pub fn build(self) -> RpcServer {
        let mut mount = Mount {
            router: Some(ConnectRouter::new()),
        };
        for s in &self.services {
            s(&mut mount);
        }
        let router = mount.router.take().expect("mount router present");
        let mut svc = ConnectRpcService::new(router).with_limits(
            Limits::default()
                .with_max_request_body_size(self.max_body_bytes)
                .with_max_message_size(self.max_body_bytes),
        );
        if !self.interceptors.is_empty() {
            svc = svc.with_interceptor(Adapter {
                chain: self.interceptors.into(),
            });
        }
        let on_panic = self.on_panic;
        let app = axum::Router::new()
            .fallback_service(svc)
            // Recovery: a panic in a handler is `internal` in the
            // protocol the caller spoke, not a dropped connection.
            .layer(CatchPanicLayer::custom(
                move |err: Box<dyn std::any::Any + Send>| {
                    let what = err
                        .downcast_ref::<&str>()
                        .map(|s| (*s).to_string())
                        .or_else(|| err.downcast_ref::<String>().cloned())
                        .unwrap_or_else(|| "panic".into());
                    if let Some(f) = &on_panic {
                        f(&what);
                    }
                    internal_response()
                },
            ))
            .layer(RequestBodyLimitLayer::new(self.max_body_bytes))
            .layer(axum::middleware::from_fn(shape_panic));
        RpcServer {
            addr: self.addr,
            app,
            up: AtomicBool::new(false),
            bound: Mutex::new(None),
            stop: CancelToken::new(),
            done: CancelToken::new(),
        }
    }
}

/// The `rpc` service.
pub struct RpcServer {
    addr: String,
    app: axum::Router,
    up: AtomicBool,
    bound: Mutex<Option<String>>,
    stop: CancelToken,
    done: CancelToken,
}

impl RpcServer {
    pub fn builder(addr: impl Into<String>) -> RpcServerBuilder {
        RpcServerBuilder::new(addr)
    }

    fn local_addr(&self) -> Option<String> {
        self.bound.lock().ok().and_then(|g| g.clone())
    }
}

/// Marks the panic response so [`shape_panic`], which sees the request,
/// can give it the caller's protocol.
const PANIC_MARK: &str = "x-kit-rpc-panic";

/// What the recovery layer answers: a Connect `internal` error, marked.
/// The layer cannot see the request, so the protocol shape comes next.
fn internal_response() -> Response<Body> {
    let body = r#"{"code":"internal","message":"internal error"}"#;
    let mut resp = Response::new(Body::from(body));
    *resp.status_mut() = StatusCode::INTERNAL_SERVER_ERROR;
    let h = resp.headers_mut();
    h.insert(
        header::CONTENT_TYPE,
        HeaderValue::from_static("application/json"),
    );
    h.insert(PANIC_MARK, HeaderValue::from_static("1"));
    resp
}

/// Outside the recovery layer: a marked panic response becomes `internal`
/// in the protocol the caller spoke. A Connect caller keeps the 500 and
/// its JSON error; a gRPC or gRPC-Web caller gets the trailers-only reply
/// its client reads a status from (HTTP 200, `grpc-status: 13`).
async fn shape_panic(req: Request, next: Next) -> Response<Body> {
    let ctype = req
        .headers()
        .get(header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .unwrap_or_default()
        .to_ascii_lowercase();
    let mut resp = next.run(req).await;
    if resp.headers_mut().remove(PANIC_MARK).is_none() {
        return resp;
    }
    if ctype.starts_with("application/grpc") {
        let ct = ctype
            .split(';')
            .next()
            .unwrap_or("application/grpc")
            .trim()
            .to_string();
        let mut out = Response::new(Body::empty());
        let h = out.headers_mut();
        if let Ok(v) = HeaderValue::from_str(&ct) {
            h.insert(header::CONTENT_TYPE, v);
        }
        h.insert("grpc-status", HeaderValue::from_static("13"));
        h.insert("grpc-message", HeaderValue::from_static("internal error"));
        return out;
    }
    resp
}

impl Service for RpcServer {
    fn name(&self) -> &str {
        SERVICE_NAME
    }

    fn start<'a>(
        &'a self,
        cancel: CancelToken,
        ready: ReadySignal,
    ) -> ServeFuture<'a, Result<(), String>> {
        Box::pin(async move {
            let listener = tokio::net::TcpListener::bind(&self.addr)
                .await
                .map_err(|e| format!("listen: {e}"))?;
            let local = listener.local_addr().map_err(|e| e.to_string())?;
            if let Ok(mut g) = self.bound.lock() {
                *g = Some(local.to_string());
            }
            self.up.store(true, Ordering::SeqCst);
            ready.report();

            let stop = self.stop.clone();
            let shutdown = async move {
                tokio::select! {
                    () = cancel.cancelled() => {}
                    () = stop.cancelled() => {}
                }
            };
            // axum::serve speaks HTTP/1.1 and, with prior knowledge,
            // unencrypted HTTP/2 on the same port: native gRPC clients
            // dial plaintext, Connect and gRPC-Web work over either.
            let res = axum::serve(
                listener,
                self.app
                    .clone()
                    .into_make_service_with_connect_info::<SocketAddr>(),
            )
            .with_graceful_shutdown(shutdown)
            .await;
            self.up.store(false, Ordering::SeqCst);
            self.done.cancel();
            res.map_err(|e| e.to_string())
        })
    }

    fn ready(&self) -> bool {
        self.up.load(Ordering::SeqCst)
    }

    fn stop<'a>(&'a self, cancel: CancelToken) -> ServeFuture<'a, Result<(), String>> {
        Box::pin(async move {
            self.up.store(false, Ordering::SeqCst);
            self.stop.cancel();
            if self.local_addr().is_some() {
                tokio::select! {
                    () = self.done.cancelled() => {}
                    () = cancel.cancelled() => {}
                }
            }
            Ok(())
        })
    }

    fn addr(&self) -> Option<String> {
        self.local_addr()
    }

    fn class(&self) -> Option<(String, String)> {
        Some(("write-shared".to_string(), "listen".to_string()))
    }
}
