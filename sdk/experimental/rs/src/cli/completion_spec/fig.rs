//! The Fig emitter: an ES module whose default export is the Fig.Spec
//! object. It carries no type annotations (JSDoc only), so it loads as
//! JavaScript and compiles as TypeScript.

use std::fmt::Write;

use super::escape::{js_string, unquote};
use super::{Arg, Command, Completion, Flag, Spec};

/// The one generator every dynamic value shares: it runs
/// `<bin> __complete <words typed so far>` and turns cobra's
/// `value\tdescription` lines into suggestions, stopping at the
/// `:<directive>` line and skipping active-help lines. `{BIN}` is the
/// binary name as a JS string literal.
const FIG_GENERATOR: &str = r#"/** @type {Fig.Generator} */
const cobraComplete = {
  script: (tokens) => [{BIN}, "__complete", ...tokens.slice(1)],
  postProcess: (out) => {
    const suggestions = [];
    for (const line of out.split("\n")) {
      if (/^:[0-9]+$/.test(line)) break;
      if (line === "" || line.startsWith("_activeHelp_ ")) continue;
      const tab = line.indexOf("\t");
      suggestions.push(
        tab < 0
          ? { name: line }
          : { name: line.slice(0, tab), description: line.slice(tab + 1) },
      );
    }
    return suggestions;
  },
};

"#;

/// Renders `s` as a Fig completion spec.
pub fn render_fig(s: &Spec) -> String {
    let name = js_string(&s.root.name);
    let mut b = format!(
        "// Generated by `{} completion fig`. Do not edit.\n\n",
        unquote(&name)
    );
    if has_dynamic(&s.root) {
        b.push_str(&FIG_GENERATOR.replace("{BIN}", &name));
    }
    b.push_str("/** @type {Fig.Spec} */\nconst completionSpec = {\n");
    command_body(&mut b, &s.root, 1, true);
    b.push_str("};\n\nexport default completionSpec;\n");
    b
}

fn has_dynamic(c: &Command) -> bool {
    c.args.iter().any(|a| a.complete == Completion::Dynamic)
        || c.flags.iter().any(|f| {
            f.arg
                .as_ref()
                .is_some_and(|a| a.complete == Completion::Dynamic)
        })
        || c.commands.iter().any(has_dynamic)
}

fn indent(depth: usize) -> String {
    "  ".repeat(depth)
}

/// Writes the fields of a command object at `depth`.
fn command_body(b: &mut String, c: &Command, depth: usize, root: bool) {
    let i = indent(depth);
    if root {
        let _ = writeln!(b, "{i}name: {},", js_string(&c.name));
    } else {
        let names: Vec<String> = std::iter::once(c.name.clone())
            .chain(c.aliases.iter().cloned())
            .collect();
        let _ = writeln!(b, "{i}name: {},", js_names(&names));
    }
    if !c.description.is_empty() {
        let _ = writeln!(b, "{i}description: {},", js_string(&c.description));
    }
    if c.hidden && !root {
        let _ = writeln!(b, "{i}hidden: true,");
    }
    let inner = indent(depth + 1);
    if !c.commands.is_empty() {
        let _ = writeln!(b, "{i}subcommands: [");
        for sub in &c.commands {
            let _ = writeln!(b, "{inner}{{");
            command_body(b, sub, depth + 2, false);
            let _ = writeln!(b, "{inner}}},");
        }
        let _ = writeln!(b, "{i}],");
    }
    if !c.flags.is_empty() {
        let _ = writeln!(b, "{i}options: [");
        for f in &c.flags {
            let _ = writeln!(b, "{inner}{{");
            option_body(b, f, depth + 2);
            let _ = writeln!(b, "{inner}}},");
        }
        let _ = writeln!(b, "{i}],");
    }
    args(b, &c.args, depth);
}

fn option_body(b: &mut String, f: &Flag, depth: usize) {
    let i = indent(depth);
    let mut names = Vec::new();
    if let Some(s) = f.short {
        names.push(format!("-{s}"));
    }
    if f.long {
        names.push(format!("--{}", f.name));
    }
    let _ = writeln!(b, "{i}name: {},", js_names(&names));
    if !f.description.is_empty() {
        let _ = writeln!(b, "{i}description: {},", js_string(&f.description));
    }
    for (on, key) in [
        (f.hidden, "hidden"),
        (f.persistent, "isPersistent"),
        (f.required, "isRequired"),
        (f.repeatable, "isRepeatable"),
        // An optional value binds only when attached with "=".
        (
            f.arg.as_ref().is_some_and(|a| a.optional),
            "requiresSeparator",
        ),
    ] {
        if on {
            let _ = writeln!(b, "{i}{key}: true,");
        }
    }
    if let Some(a) = &f.arg {
        args(b, std::slice::from_ref(a), depth);
    }
}

/// Writes `args:` as one object, or an array of several.
fn args(b: &mut String, args: &[Arg], depth: usize) {
    let i = indent(depth);
    match args {
        [] => {}
        [a] => {
            let _ = writeln!(b, "{i}args: {{");
            arg_body(b, a, depth + 1);
            let _ = writeln!(b, "{i}}},");
        }
        _ => {
            let inner = indent(depth + 1);
            let _ = writeln!(b, "{i}args: [");
            for a in args {
                let _ = writeln!(b, "{inner}{{");
                arg_body(b, a, depth + 2);
                let _ = writeln!(b, "{inner}}},");
            }
            let _ = writeln!(b, "{i}],");
        }
    }
}

fn arg_body(b: &mut String, a: &Arg, depth: usize) {
    let i = indent(depth);
    let _ = writeln!(b, "{i}name: {},", js_string(&a.name));
    if a.optional {
        let _ = writeln!(b, "{i}isOptional: true,");
    }
    if a.variadic {
        let _ = writeln!(b, "{i}isVariadic: true,");
    }
    match &a.complete {
        Completion::None => {}
        Completion::Choices(v) => {
            let _ = writeln!(b, "{i}suggestions: {},", js_array(v));
        }
        Completion::File(_) => {
            let _ = writeln!(b, "{i}template: \"filepaths\",");
        }
        Completion::Dir => {
            let _ = writeln!(b, "{i}template: \"folders\",");
        }
        Completion::Dynamic => {
            let _ = writeln!(b, "{i}generators: cobraComplete,");
        }
    }
}

/// A single name as a string, several as an array.
fn js_names(names: &[String]) -> String {
    match names {
        [one] => js_string(one),
        _ => js_array(names),
    }
}

fn js_array(vals: &[String]) -> String {
    let q: Vec<String> = vals.iter().map(|v| js_string(v)).collect();
    format!("[{}]", q.join(", "))
}
