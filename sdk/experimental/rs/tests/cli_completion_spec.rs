//! `completion fig` and `completion usage` on a [`Root`], and the clap
//! rules the shared corpus cannot express. Ports Go
//! `console/cli/completionspec` command_test.go.

#![cfg(feature = "cli")]

use hop_top_kit::cli::completion::{bind_args, bind_flag, dir, file, func, static_values, Item};
use hop_top_kit::cli::completion_spec::{render_usage, Completion, Spec};
use hop_top_kit::cli::{ArgSpec, CommandSpec, FlagSpec, Root};

/// A root with one leaf carrying a scoped enum flag (static) and a
/// completer-bound flag (dynamic).
fn spec_root() -> Root {
    let list = CommandSpec::new("list")
        .about("list widgets")
        .flag(FlagSpec::string("status").help("widget status"))
        .flag(FlagSpec::string("owner").help("widget owner"));
    let cmd = CommandSpec::new("spectool")
        .version("0.1.0", Some('V'))
        .about("spec test tool")
        .subcommand(list)
        .subcommand(CommandSpec::new("status").about("tool status"));
    let mut root = Root::new(cmd);
    bind_flag(&mut root, "list", "owner", static_values(["ann", "bob"]));
    root.with_command_flag_enum("list", "status", ["TODO", "DONE"]);
    root
}

fn run(root: &Root, args: &[&str]) -> String {
    let (mut out, mut err) = (Vec::new(), Vec::new());
    let argv = std::iter::once("spectool").chain(args.iter().copied());
    root.try_builtin(argv, &mut out, &mut err)
        .expect("a builtin")
        .expect("no error");
    String::from_utf8(out).unwrap()
}

#[test]
fn completion_fig_command() {
    let out = run(&spec_root(), &["completion", "fig"]);
    assert!(
        out.starts_with("// Generated by `spectool completion fig`. Do not edit.\n"),
        "{out}"
    );
    assert!(out.contains(r#"script: (tokens) => ["spectool", "__complete", ...tokens.slice(1)],"#));
    assert!(
        out.contains(r#"suggestions: ["TODO", "DONE"],"#),
        "enum values are static"
    );
    assert!(
        out.contains("generators: cobraComplete,"),
        "a bound completer calls back"
    );
    assert!(out.ends_with("export default completionSpec;\n"), "{out}");
}

#[test]
fn completion_usage_command() {
    let out = run(&spec_root(), &["completion", "usage"]);
    assert!(
        out.starts_with("// Generated by `spectool completion usage`. Do not edit.\n"),
        "{out}"
    );
    assert!(out.contains("\nbin \"spectool\"\n"));
    assert!(out.contains("\nversion \"0.1.0\"\n"));
    assert!(out.contains(r#"choices strict=#false "TODO" "DONE""#));
    assert!(out.contains(r#"complete run="spectool __complete"#));
}

/// The exports sit next to the shell scripts, once each, and the shell
/// leaves keep working.
#[test]
fn completion_spec_commands_sit_under_completion() {
    let root = spec_root();
    let model = root.model();
    let comp = model.find("completion").expect("completion");
    let names: Vec<&str> = comp.commands.iter().map(|c| c.name.as_str()).collect();
    for n in ["bash", "fig", "usage"] {
        assert_eq!(
            names.iter().filter(|x| **x == n).count(),
            1,
            "{n} in {names:?}"
        );
    }
    assert!(run(&root, &["completion", "bash"]).contains("bash completion"));
}

/// The completion command is hidden, as default help shows it.
#[test]
fn completion_spec_hides_management_group() {
    let out = run(&spec_root(), &["completion", "usage"]);
    assert!(out.contains(
        r#"cmd "completion" help="Generate the autocompletion script for the specified shell" hide=#true {"#
    ));
    assert!(out.contains("    cmd \"fig\" help=\"Generate a Fig completion spec\"\n"));
}

/// cobra's NoFileCompletions on the export leaves: nothing to complete,
/// and no argument in the spec.
#[test]
fn completion_spec_leaves_complete_nothing() {
    let root = spec_root();
    for leaf in ["fig", "usage"] {
        assert_eq!(run(&root, &["__complete", "completion", leaf, ""]), ":4\n");
    }
    let spec = Spec::from_root(&root);
    let comp = spec
        .root
        .commands
        .iter()
        .find(|c| c.name == "completion")
        .unwrap();
    assert!(comp.args.is_empty());
    assert!(comp.commands.iter().all(|c| c.args.is_empty()), "{comp:?}");
}

/// A root with the default completion command disabled (cobra's
/// `CompletionOptions.DisableDefaultCmd`) has no exports either.
#[test]
fn disabled_completion_command_has_no_exports() {
    let mut root = spec_root();
    root.disable_completion_command();
    assert!(root.model().find("completion").is_none());
    let (mut out, mut err) = (Vec::new(), Vec::new());
    assert!(root
        .try_builtin(["spectool", "completion", "fig"], &mut out, &mut err)
        .is_none());
    let spec = Spec::from_root(&root);
    assert!(spec.root.commands.iter().all(|c| c.name != "completion"));
}

/// The default-missing value is read off the live tree even when the
/// command requires positionals and flags the probe does not give.
#[test]
fn optional_value_flag_reads_default_missing() {
    let cmd = CommandSpec::new("tool").subcommand(
        CommandSpec::new("run")
            .arg(ArgSpec::new("job").required())
            .flag(FlagSpec::string("token").required())
            .flag(
                FlagSpec::string("wait")
                    .value_name("duration")
                    .no_opt_default("30s"),
            ),
    );
    let mut root = Root::new(cmd);
    root.disable_completion_command();
    let out = render_usage(&Spec::from_root(&root));
    assert!(
        out.contains(
            "flag \"--wait <duration>\" default_missing=\"30s\" require_equals=#true {\n        complete type=\"none\"\n    }\n"
        ),
        "{out}"
    );
}

/// Flags inherited from an ancestor's global flag belong to the
/// ancestor; clap's help and version flags follow cobra's.
#[test]
fn global_flags_belong_to_their_declaring_command() {
    let cmd = CommandSpec::new("tool")
        .version("2.0.0", Some('V'))
        .flag(FlagSpec::bool("verbose").persistent())
        .subcommand(CommandSpec::new("run"));
    let mut root = Root::new(cmd);
    root.disable_completion_command();
    let spec = Spec::from_root(&root);
    let names: Vec<&str> = spec.root.flags.iter().map(|f| f.name.as_str()).collect();
    assert_eq!(names, ["verbose", "version"]);
    let version = &spec.root.flags[1];
    assert_eq!(version.short, Some('V'), "clap's own version flag");
    assert_eq!(version.description, "version for tool");
    assert!(spec.root.flags[0].persistent);
    assert!(
        spec.root.commands[0].flags.is_empty(),
        "{:?}",
        spec.root.commands[0]
    );
}

/// A completer's kind is read without running it: file and dir
/// completers are spec-visible, any other calls back.
#[test]
fn completer_kinds_map_to_spec_completions() {
    let cmd = CommandSpec::new("tool").subcommand(
        CommandSpec::new("run")
            .flag(FlagSpec::string("conf"))
            .flag(FlagSpec::string("out"))
            .flag(FlagSpec::string("who"))
            .arg(ArgSpec::new("job")),
    );
    let mut root = Root::new(cmd);
    root.disable_completion_command();
    bind_flag(&mut root, "run", "conf", file([".toml"]));
    bind_flag(&mut root, "run", "out", dir());
    bind_flag(&mut root, "run", "who", func(|_, _| panic!("never run")));
    bind_args(&mut root, "run", func(|_, _| Ok(vec![Item::new("x")])));
    let spec = Spec::from_root(&root);
    let run = &spec.root.commands[0];
    let kinds: Vec<&Completion> = run
        .flags
        .iter()
        .map(|f| &f.arg.as_ref().unwrap().complete)
        .collect();
    assert_eq!(
        kinds,
        [
            &Completion::File(vec!["toml".into()]),
            &Completion::Dir,
            &Completion::Dynamic
        ]
    );
    assert_eq!(run.args[0].name, "job");
    assert!(run.args[0].optional);
    assert_eq!(run.args[0].complete, Completion::Dynamic);
}

/// Root aliases are completed by the root's positional completion, so
/// the root gets a callback, as Go's alias wrapper gives it.
#[test]
fn root_aliases_call_back() {
    let cmd = CommandSpec::new("tool")
        .subcommand(CommandSpec::new("a").subcommand(CommandSpec::new("b")));
    let mut root = Root::new(cmd);
    root.disable_completion_command();
    root.alias("ab", "a b").unwrap();
    let spec = Spec::from_root(&root);
    assert_eq!(spec.root.args.len(), 1);
    assert_eq!(spec.root.args[0].complete, Completion::Dynamic);
    let shim = spec.root.commands.iter().find(|c| c.name == "ab").unwrap();
    assert!(shim.hidden && shim.args.is_empty(), "{shim:?}");
}

/// A default-missing value the flag's own parser rejects is unknown,
/// so it is left out rather than written as "".
#[test]
fn rejected_default_missing_is_left_out() {
    let cmd = CommandSpec::new("tool").flag(FlagSpec::uint("typed").no_opt_default("auto"));
    let mut root = Root::new(cmd);
    root.disable_completion_command();
    let usage = render_usage(&Spec::from_root(&root));
    assert!(
        usage.contains("\nflag \"--typed <uint>\" require_equals=#true {\n"),
        "{usage}"
    );
    assert!(!usage.contains("default_missing"), "{usage}");
}

/// An empty value name is cobra's `value`.
#[test]
fn empty_value_name_is_value() {
    let cmd = CommandSpec::new("tool").flag(FlagSpec::string("bt").value_name(""));
    let mut root = Root::new(cmd);
    root.disable_completion_command();
    let usage = render_usage(&Spec::from_root(&root));
    assert!(usage.contains("\nflag \"--bt <value>\"\n"), "{usage}");
}
