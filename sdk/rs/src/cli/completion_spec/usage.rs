//! The Usage emitter: a KDL v2 spec for usage.jdx.dev.

use std::fmt::Write;

use super::escape::{kdl_string, unquote, usage_bin};
use super::{Command, Completion, Flag, Spec};

/// The `complete run=` command for a dynamic value. usage renders it as
/// a Tera template and runs it with `sh -c`: the words typed so far, up
/// to the cursor and without the binary name, become shell-quoted
/// `__complete` arguments; cobra's stderr note is dropped, since usage
/// passes stderr through to the terminal; and awk turns cobra's
/// `value\tdescription` lines into usage's `value:description` (a colon
/// in the value escaped), stopping at the `:<directive>` line and
/// skipping active-help lines. It follows the binary name, written as a
/// shell word.
const RUN_TAIL: &str = concat!(
    r#" __complete{% for w in words %}{% if loop.index0 > 0 and loop.index0 <= CURRENT %} {{ w | shell_quote }}{% endif %}{% endfor %} 2>/dev/null"#,
    r#" | awk -F '\t' '/^:[0-9]+$/ { exit } /^_activeHelp_ / { next } { v = $1; gsub(/:/, "\\:", v); if (NF > 1) print v ":" $2; else print v }'"#,
);

/// What a value completes to in Usage: a spec completion, or nothing at
/// all (`type="none"`, no file fallback) for an optional value.
enum Value<'a> {
    Spec(&'a Completion),
    NoValue,
}

/// Renders `s` as a Usage KDL spec (KDL v2).
pub fn render_usage(s: &Spec) -> String {
    let name = kdl_string(&s.root.name);
    let mut b = format!(
        "// Generated by `{} completion usage`. Do not edit.\n",
        unquote(&name)
    );
    let _ = writeln!(b, "name {name}");
    let _ = writeln!(b, "bin {name}");
    if !s.version.is_empty() {
        let _ = writeln!(b, "version {}", kdl_string(&s.version));
    }
    if !s.root.description.is_empty() {
        let _ = writeln!(b, "about {}", kdl_string(&s.root.description));
    }
    let run = usage_bin(&s.root.name) + RUN_TAIL;
    body(&mut b, &s.root, 0, &run);
    b
}

fn indent(depth: usize) -> String {
    "    ".repeat(depth)
}

/// Writes a command's aliases, flags, args and subcommands.
fn body(b: &mut String, c: &Command, depth: usize, run: &str) {
    let i = indent(depth);
    if !c.aliases.is_empty() {
        let _ = writeln!(b, "{i}alias {}", kdl_strings(&c.aliases));
    }
    for f in &c.flags {
        flag(b, f, depth, run);
    }
    for a in &c.args {
        let name = if a.optional {
            format!("[{}]", a.name)
        } else {
            format!("<{}>", a.name)
        };
        let _ = write!(b, "{i}arg {}", kdl_string(&name));
        if a.variadic {
            b.push_str(" var=#true");
        }
        complete(b, Value::Spec(&a.complete), depth, run);
    }
    for sub in &c.commands {
        let _ = write!(b, "{i}cmd {}", kdl_string(&sub.name));
        if !sub.description.is_empty() {
            let _ = write!(b, " help={}", kdl_string(&sub.description));
        }
        if sub.hidden {
            b.push_str(" hide=#true");
        }
        if sub.aliases.is_empty()
            && sub.flags.is_empty()
            && sub.args.is_empty()
            && sub.commands.is_empty()
        {
            b.push('\n');
            continue;
        }
        b.push_str(" {\n");
        body(b, sub, depth + 1, run);
        let _ = writeln!(b, "{i}}}");
    }
}

fn flag(b: &mut String, f: &Flag, depth: usize, run: &str) {
    let mut usage = Vec::new();
    if let Some(s) = f.short {
        usage.push(format!("-{s}"));
    }
    if f.long {
        usage.push(format!("--{}", f.name));
    }
    if let Some(a) = &f.arg {
        usage.push(format!("<{}>", a.name));
    }
    let _ = write!(b, "{}flag {}", indent(depth), kdl_string(&usage.join(" ")));
    if !f.description.is_empty() {
        let _ = write!(b, " help={}", kdl_string(&f.description));
    }
    for (on, key) in [
        (f.persistent, "global"),
        (f.required, "required"),
        (f.hidden, "hide"),
        (f.repeatable && f.arg.is_none(), "count"),
        (f.repeatable && f.arg.is_some(), "var"),
    ] {
        if on {
            let _ = write!(b, " {key}=#true");
        }
    }
    match &f.arg {
        // An optional value: bare means default_missing, a value must be
        // attached. usage's completer still reads the next word as the
        // value, where the program reads a positional, so no candidates
        // are offered for it.
        Some(a) if a.optional => {
            if let Some(d) = &f.default_missing {
                let _ = write!(b, " default_missing={}", kdl_string(d));
            }
            b.push_str(" require_equals=#true");
            complete(b, Value::NoValue, depth, run);
        }
        Some(a) => complete(b, Value::Spec(&a.complete), depth, run),
        None => complete(b, Value::Spec(&Completion::None), depth, run),
    }
}

/// Ends the current node: bare when there is nothing to complete, else
/// with a child block holding the choices or completer. Choices are
/// advisory (`strict=#false`): neither kit enums nor clap's possible
/// values are enforced by the spec.
fn complete(b: &mut String, v: Value<'_>, depth: usize, run: &str) {
    let child = match v {
        Value::Spec(Completion::None) => {
            b.push('\n');
            return;
        }
        Value::Spec(Completion::Choices(v)) => format!("choices strict=#false {}", kdl_strings(v)),
        Value::Spec(Completion::File(exts)) => {
            let mut typ = String::from("file");
            if !exts.is_empty() {
                typ = format!("file:{}", exts.join(","));
            }
            format!("complete type={}", kdl_string(&typ))
        }
        Value::Spec(Completion::Dir) => r#"complete type="dir""#.to_string(),
        Value::Spec(Completion::Dynamic) => {
            format!("complete run={} descriptions=#true", kdl_string(run))
        }
        Value::NoValue => r#"complete type="none""#.to_string(),
    };
    let _ = write!(
        b,
        " {{\n{}{child}\n{}}}\n",
        indent(depth + 1),
        indent(depth)
    );
}

fn kdl_strings(vals: &[String]) -> String {
    let q: Vec<String> = vals.iter().map(|v| kdl_string(v)).collect();
    q.join(" ")
}
