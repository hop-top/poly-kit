/// Where an argument's candidate values come from.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum Completion {
    /// The spec offers nothing for the value.
    #[default]
    None,
    /// A fixed list.
    Choices(Vec<String>),
    /// File paths, filtered by these extensions (no leading dot) when
    /// any are given.
    File(Vec<String>),
    /// Directory paths.
    Dir,
    /// The binary's `__complete` entry computes the values when asked.
    Dynamic,
}

/// A positional argument, or the value a flag takes.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Arg {
    /// The value name.
    pub name: String,
    /// Whether the argument may be left out.
    pub optional: bool,
    /// Whether the argument takes several values.
    pub variadic: bool,
    /// Where its candidates come from.
    pub complete: Completion,
}

/// One flag declared on a command.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Flag {
    /// The long name without dashes; the id for a short-only flag.
    pub name: String,
    /// Whether `name` is a long name; false for a short-only flag.
    pub long: bool,
    /// The one-letter shorthand.
    pub short: Option<char>,
    /// The help text.
    pub description: String,
    /// A `global` flag: it applies to the declaring command and every
    /// command below it.
    pub persistent: bool,
    /// Left out of help; still parses.
    pub hidden: bool,
    /// Must be given.
    pub required: bool,
    /// May be given more than once: counters, and flags collecting a
    /// list.
    pub repeatable: bool,
    /// The value the flag takes; `None` for a switch. When
    /// `Arg::optional`, the value must be attached (`--flag=value`) and
    /// a bare flag means `default_missing`.
    pub arg: Option<Arg>,
    /// The value of a bare optional-value flag; `None` when it cannot
    /// be read (the flag's own parser rejects it).
    pub default_missing: Option<String>,
}

/// One node of the command tree.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Command {
    /// The command name; the binary name at the root.
    pub name: String,
    /// Other names, in declaration order.
    pub aliases: Vec<String>,
    /// The one-line description.
    pub description: String,
    /// Hidden commands still parse; terminals just do not suggest them.
    pub hidden: bool,
    /// Flags declared here, sorted by name.
    pub flags: Vec<Flag>,
    /// Positionals, in order.
    pub args: Vec<Arg>,
    /// Subcommands, sorted by name.
    pub commands: Vec<Command>,
}

/// The whole tree. `root.name` is the binary name; `version` is the
/// root's version, empty when it has none.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Spec {
    /// The root command.
    pub root: Command,
    /// The root's version.
    pub version: String,
}

