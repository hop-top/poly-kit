//! Completion specs for terminals that read one instead of running a
//! shell script: a Fig spec (VS Code terminal suggest, Kiro CLI,
//! inshellisense, Warp) and a Usage KDL spec (usage.jdx.dev, mise).
//! Ports Go `console/cli/completionspec`.
//!
//! One model, built from the live tree of a [`Root`] by
//! [`Spec::from_root`], feeds both emitters ([`render_fig`],
//! [`render_usage`]). Values the tree states statically (flag enums,
//! clap possible values, [`file()`] and [`dir`] completers) are written
//! into the spec. Values any other completer computes become a generator
//! that calls back into the binary's hidden `__complete` entry, so the
//! spec never snapshots data that changes.
//!
//! Output is byte-stable: commands and flags are sorted by name, and the
//! emitters are pure functions of the model. `contracts/completion-spec-v1`
//! pins the bytes every port must produce.
//!
//! # Example
//!
//! ```
//! use hop_top_kit::cli::completion_spec::{render_usage, Spec};
//! use hop_top_kit::cli::{ArgSpec, CommandSpec, Root, ValueSpec};
//!
//! let deploy = CommandSpec::new("deploy")
//!     .about("Deploy")
//!     .arg(
//!         ArgSpec::new("env")
//!             .required()
//!             .allowed_values([ValueSpec::new("prod"), ValueSpec::new("staging")]),
//!     );
//! let mut root = Root::new(CommandSpec::new("tool").about("Example tool").subcommand(deploy));
//! root.disable_completion_command();
//!
//! assert_eq!(
//!     render_usage(&Spec::from_root(&root)),
//!     "// Generated by `tool completion usage`. Do not edit.\n\
//!      name \"tool\"\n\
//!      bin \"tool\"\n\
//!      about \"Example tool\"\n\
//!      cmd \"deploy\" help=\"Deploy\" {\n\
//!      \x20   arg \"<env>\" {\n\
//!      \x20       choices strict=#false \"prod\" \"staging\"\n\
//!      \x20   }\n\
//!      }\n",
//! );
//! ```
//!
//! # Differences from Go
//!
//! - The walker reads clap, not cobra: `about` is the description, a
//!   `global` flag is persistent, `Count` and `Append` actions repeat, and
//!   a value flag with `require_equals` whose `num_args` admits zero
//!   values takes an optional, attached-only value (pflag's
//!   `NoOptDefVal`). Without `require_equals` clap binds the next word,
//!   so such a flag is a plain value flag. The `default_missing_value` is
//!   read by parsing the bare flag, since clap has no getter for it; that
//!   runs the flag's value parser once, and a value it rejects is left
//!   out.
//! - An empty value name is `value`, as in cobra.
//! - Version and help flags are clap's own (`-V`, not cobra's `-v`); the
//!   version flag's text is cobra's, as `__complete` prints it.
//! - Candidates are per positional: its possible values, else the
//!   command's bound completer. A [`file()`] or [`dir`] completer is
//!   written into the spec instead of calling back.
//! - Hidden positionals (a deep alias shim's) are left out.
//!
//! [`Root`]: crate::cli::Root
//! [`file()`]: crate::cli::completion::file
//! [`dir`]: crate::cli::completion::dir

