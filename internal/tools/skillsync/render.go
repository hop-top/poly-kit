package main

import (
	"errors"
	"fmt"
	"strings"
)

const generatedNote = "Generated by `make skills-sync` from the capability parity page. Do not edit by hand."

func (g *gen) repoURL(s *skill) string { return g.ports.Host + "/" + s.Comp.Mirror }

// skillURL is the canonical URL of a skill: its SKILL.md in the mirror that
// publishes it.
func (g *gen) skillURL(s *skill) string {
	return fmt.Sprintf("%s/blob/%s/skills/%s/SKILL.md", g.repoURL(s), g.ports.MirrorBranch, s.Spec.Skill)
}

// docsURL links a file of the documentation repository. The branch is the
// one docs.branch value of ports.yaml.
func (g *gen) docsURL(rel string) string {
	return fmt.Sprintf("%s/%s/blob/%s/%s", g.ports.Host, g.ports.Docs.Repo, g.ports.Docs.Branch, rel)
}

func (g *gen) parityURL() string { return g.docsURL(g.o.Parity) }

func (g *gen) router() *skill { return g.skills[0] }

func (g *gen) matrixURL() string {
	r := g.router()
	return fmt.Sprintf("%s/blob/%s/skills/%s/references/capability-matrix.md", g.repoURL(r), g.ports.MirrorBranch, r.Spec.Skill)
}

func (g *gen) portSkills() []*skill { return g.skills[1:] }

// tier is the tier of a port: the tiers page row naming its directory, or
// the label ports.yaml gives a port that has no row.
func (g *gen) tier(s *skill) (string, error) {
	row, listed := g.tiers[s.Comp.Dir]
	switch {
	case listed && s.Spec.Tier != "":
		return "", fmt.Errorf("%s: tier given twice (tiers page says %q, ports.yaml says %q)", s.Spec.Component, row, s.Spec.Tier)
	case listed:
		return row, nil
	case s.Spec.Tier != "":
		return s.Spec.Tier, nil
	}
	return "", fmt.Errorf("%s: no tier: the tiers page has no row naming %q and ports.yaml sets none", s.Spec.Component, s.Comp.Dir)
}

func (g *gen) pkg(s *skill) (string, error) {
	switch {
	case s.Comp.Package != "" && s.Spec.Package != "" && s.Comp.Package != s.Spec.Package:
		return "", fmt.Errorf("%s: package %q in the publish matrix, %q in ports.yaml", s.Spec.Component, s.Comp.Package, s.Spec.Package)
	case s.Comp.Package != "":
		return s.Comp.Package, nil
	case s.Spec.Package != "":
		return s.Spec.Package, nil
	}
	return "", fmt.Errorf("%s: no package in the publish matrix or ports.yaml", s.Spec.Component)
}

// validatePorts resolves the tier and package of every port, so a missing
// one fails the run whether or not the port's skill exists yet.
func (g *gen) validatePorts() error {
	var errs []error
	for _, s := range g.portSkills() {
		if _, err := g.tier(s); err != nil {
			errs = append(errs, err)
		}
		if _, err := g.pkg(s); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// refCol is the index of the reference column (Go).
func (g *gen) refCol() int {
	for i, s := range g.colSpec {
		if s.Column == g.ports.ReferenceColumn {
			return i
		}
	}
	return 0
}

func (g *gen) vocabTable() string {
	var b strings.Builder
	b.WriteString("| Status | Meaning |\n|---|---|\n")
	for _, w := range statusOrder {
		fmt.Fprintf(&b, "| %s | %s |\n", w, escapeCell(g.par.Vocab[w]))
	}
	return b.String()
}

// capabilityMatrix is the router's references/capability-matrix.md.
func (g *gen) capabilityMatrix() string {
	var b strings.Builder
	b.WriteString("# Capability matrix\n\n" + generatedNote + "\n\n")
	fmt.Fprintf(&b, "Source of truth: [capability parity](%s), whose Evidence column explains the path prefixes.\n\n", g.parityURL())
	b.WriteString(g.vocabTable())
	for _, sec := range g.par.Sections {
		fmt.Fprintf(&b, "\n## %s\n\n| Capability | %s | Evidence |\n|---|%s---|\n", sec.Title, strings.Join(g.par.Columns, " | "), strings.Repeat("---|", len(g.par.Columns)))
		for _, c := range sec.Caps {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", escapeCell(c.Name), strings.Join(c.Status, " | "), escapeCell(c.Evidence))
		}
	}
	return b.String()
}

type secNames struct {
	Title string
	Names []string
}

// goOnlySections lists capabilities every other SDK lacks, by section.
func (g *gen) goOnlySections() []secNames {
	var out []secNames
	for _, sec := range g.par.Sections {
		var names []string
		for _, c := range sec.Caps {
			if c.goOnly(g.refCol()) {
				names = append(names, c.Name)
			}
		}
		if len(names) > 0 {
			out = append(out, secNames{sec.Title, names})
		}
	}
	return out
}

func (g *gen) goOnlyPage() string {
	var b strings.Builder
	b.WriteString("# Go-only capabilities\n\n" + generatedNote + "\n\n")
	fmt.Fprintf(&b, "Source of truth: [capability parity](%s).\n\n", g.parityURL())
	b.WriteString("Every other SDK has status `none` or `n/a` for these. When a task needs one, use the Go port or run the `kit` binary as a sidecar.\n")
	total := 0
	for _, s := range g.goOnlySections() {
		fmt.Fprintf(&b, "\n## %s\n\n", s.Title)
		for _, n := range s.Names {
			fmt.Fprintf(&b, "- %s\n", n)
		}
		total += len(s.Names)
	}
	if total == 0 {
		b.WriteString("\nNone.\n")
	}
	return b.String()
}

// portsTable is the table of ports: one row per port skill.
func (g *gen) portsTable(extra bool) string {
	var b strings.Builder
	head := "| Port | Skill | Package | Install | Tier | Status counts |"
	sep := "|---|---|---|---|---|---|"
	if extra {
		head = "| Port | Skill | Package | Install | Tier | Needs | Status counts |"
		sep = "|---|---|---|---|---|---|---|"
	}
	b.WriteString(head + "\n" + sep + "\n")
	for _, s := range g.portSkills() {
		tier, _ := g.tier(s) // validated by validatePorts
		pkg, _ := g.pkg(s)
		counts := formatCounts(g.par.Counts(s.Col))
		if extra {
			fmt.Fprintf(&b, "| %s | [`%s`](%s) | `%s` | `%s` | %s | %s | %s |\n", s.Spec.Language, s.Spec.Skill, g.skillURL(s), pkg, escapeCell(s.Spec.Install), tier, s.Spec.Toolchain, counts)
		} else {
			fmt.Fprintf(&b, "| %s | [`%s`](%s) | `%s` | `%s` | %s | %s |\n", s.Spec.Language, s.Spec.Skill, g.skillURL(s), pkg, escapeCell(s.Spec.Install), tier, counts)
		}
	}
	return b.String()
}

// portsBlock is the body of the router's `ports` managed block.
func (g *gen) portsBlock() string {
	return g.portsTable(false)
}

func joinNames(n []string) string {
	if len(n) == 0 {
		return "nothing"
	}
	return strings.Join(n, ", ")
}

// coverageBlock is the body of a port skill's `coverage` managed block.
func (g *gen) coverageBlock(s *skill) string {
	tier, _ := g.tier(s)
	var b strings.Builder
	fmt.Fprintf(&b, "Tier: %s.\n\n", tier)
	for _, sec := range g.par.Sections {
		var lacks, has []string
		for _, c := range sec.Caps {
			switch c.Status[s.Col] {
			case stNone:
				lacks = append(lacks, c.Name)
			case stNA:
			default:
				has = append(has, c.Name)
			}
		}
		if len(lacks) <= len(has) {
			fmt.Fprintf(&b, "- %s. Lacks: %s.\n", sec.Title, joinNames(lacks))
		} else {
			fmt.Fprintf(&b, "- %s. Has only: %s.\n", sec.Title, joinNames(has))
		}
	}
	return b.String()
}

// coveragePage is a port skill's references/coverage.md.
func (g *gen) coveragePage(s *skill) string {
	tier, _ := g.tier(s)
	var b strings.Builder
	fmt.Fprintf(&b, "# %s coverage\n\n%s\n\n", s.Spec.Language, generatedNote)
	fmt.Fprintf(&b, "Tier: %s. Needs %s. Source of truth: [capability parity](%s).\n", tier, s.Spec.Toolchain, g.parityURL())
	counts := g.par.Counts(s.Col)
	for _, st := range statusOrder {
		if counts[st] == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s (%d)\n\n%s.\n\n", st, counts[st], strings.TrimSuffix(g.par.Vocab[st], "."))
		for _, sec := range g.par.Sections {
			var names []string
			for _, c := range sec.Caps {
				if c.Status[s.Col] != st {
					continue
				}
				if st == stPartial {
					fmt.Fprintf(&b, "- %s (%s): %s\n", c.Name, sec.Title, c.Evidence)
				} else {
					names = append(names, c.Name)
				}
			}
			if len(names) > 0 {
				fmt.Fprintf(&b, "- %s: %s\n", sec.Title, strings.Join(names, ", "))
			}
		}
	}
	return b.String()
}

// otherPorts is references/other-ports.md, byte-identical in every port
// skill: nothing in it depends on which skill it sits in.
func (g *gen) otherPorts() string {
	t := g.portsTable(true)
	var b strings.Builder
	b.WriteString("# Other ports\n\n" + generatedNote + "\n\n")
	fmt.Fprintf(&b, "This file is a snapshot taken at the `metadata.version` recorded in this skill's SKILL.md. The current matrix is [capability-matrix](%s); its source is [capability parity](%s).\n\n", g.matrixURL(), g.parityURL())
	b.WriteString("## Ports\n\n" + t)
	fmt.Fprintf(&b, "\n## Router\n\nTo choose between ports, use [`%s`](%s).\n\n## Go only\n\nNo other port has these (status `none` or `n/a`); use Go or run the `kit` binary as a sidecar.\n\n", g.router().Spec.Skill, g.skillURL(g.router()))
	secs := g.goOnlySections()
	for _, s := range secs {
		fmt.Fprintf(&b, "- %s: %s\n", s.Title, strings.Join(s.Names, ", "))
	}
	if len(secs) == 0 {
		b.WriteString("None.\n")
	}
	return b.String()
}
