// Package kitinit — releaseplease_preflight.go renders
// `.github/workflows/release-please-preflight.yml`, the caller of
// hop-top/.github's release-please-preflight.yml reusable workflow. It
// checks the release-please config, manifest and callers on every pull
// request, so a misconfigured release fails the PR instead of the first
// release. The reusable workflow takes no required inputs or secrets and
// accepts a repo without publish.yml when every package is `go`.
//
// Rendered with the release-please caller (Inputs.WithReleasePlease): the
// preflight reports a missing release-please.yml as a failure. Standard
// Section 6 conflict policy (applyWorkflow).
package kitinit

import (
	"path/filepath"
	"time"
)

const (
	preflightCallerRel = ".github/workflows/release-please-preflight.yml"
	preflightReusable  = "release-please-preflight.yml"
)

// renderPreflightCaller produces the preflight caller. No `paths:` filter
// on the triggers: a required check whose workflow a filter skipped never
// reports and leaves the PR pending.
func renderPreflightCaller() string {
	return "# Generated by `kit init`. Edits will not be overwritten;\n" +
		"# kit will surface conflicting refreshes as `.kit-suggested` siblings.\n" +
		"# Checks the release-please config, manifest and workflows on every pull\n" +
		"# request via the hop-top/.github release-please-preflight reusable workflow.\n\n" +
		"name: release-please-preflight\n\n" +
		"on:\n  pull_request:\n  workflow_dispatch: {}\n\n" +
		"permissions:\n  contents: read\n\n" +
		"jobs:\n  preflight:\n" +
		"    uses: " + workflowCallerUses(preflightReusable) + "\n"
}

// renderPreflight applies the preflight caller to target, updating
// `.kit/generated.json`. Honors in.DryRun.
func renderPreflight(target string, in Inputs, now func() time.Time) ([]WorkflowAction, error) {
	if now == nil {
		now = time.Now
	}
	manifestPath := filepath.Join(target, filepath.FromSlash(manifestRelPath))
	manifest, err := readManifest(manifestPath)
	if err != nil {
		return nil, err
	}
	content := renderPreflightCaller()
	p := plannedWorkflow{
		RelPath:     preflightCallerRel,
		AbsPath:     filepath.Join(target, filepath.FromSlash(preflightCallerRel)),
		Content:     content,
		ContentHash: sha256Hex([]byte(content)),
	}
	a, err := applyWorkflow(p, manifest, manifest.index(), in.DryRun, now)
	if err != nil {
		return nil, err
	}
	if !in.DryRun {
		if err := writeWorkflowManifest(manifestPath, manifest); err != nil {
			return nil, err
		}
	}
	return []WorkflowAction{a}, nil
}
