func TestGather_ReleasePleaseFlags(t *testing.T) {
	in, err := Gather(t.Context(), []string{"demo"}, &FlagSet{}, tmpl.Manifest{}, Defaults{}, nil)
	require.NoError(t, err)
	assert.True(t, in.WithReleasePlease, "release-please caller is on by default")
	assert.False(t, in.MigrateReleasePlease, "migration is opt-in")

	off, on := false, true
	in, err = Gather(t.Context(), []string{"demo"},
		&FlagSet{WithReleasePlease: &off, MigrateReleasePlease: &on}, tmpl.Manifest{}, Defaults{}, nil)
	require.NoError(t, err)
	assert.False(t, in.WithReleasePlease)
	assert.True(t, in.MigrateReleasePlease)
}

func TestApplyReleasePleaseFlags(t *testing.T) {
	cases := []struct {
		argv        []string
		wantWith    *bool
		wantMigrate *bool
	}{
		{nil, nil, nil},
		{[]string{"--without-release-please"}, boolp(false), nil},
		{[]string{"--with-release-please=false"}, boolp(false), nil},
		{[]string{"--with-release-please", "--without-release-please"}, boolp(false), nil},
		{[]string{"--migrate-release-please"}, nil, boolp(true)},
	}
	for _, c := range cases {
		cmd := InitCmd(nil)
		require.NoError(t, cmd.ParseFlags(c.argv))
		fs := &FlagSet{}
		applyReleasePleaseFlags(cmd, fs)
		assert.Equal(t, c.wantWith, fs.WithReleasePlease, "%v", c.argv)
		assert.Equal(t, c.wantMigrate, fs.MigrateReleasePlease, "%v", c.argv)
	}
}

func boolp(b bool) *bool { return &b }

