func TestRenderReleasePleaseCaller_RoundTripsThroughClassifier(t *testing.T) {
	for _, s := range []releasePleaseSettings{
		{Branches: []string{"main"}, Dispatch: true},
		{Branches: []string{"main", "next"}, Dispatch: true, TargetBranch: "next"},
		{Dispatch: true, ConfigFile: "rp.json", ManifestFile: "rp-manifest.json"},
		{Branches: []string{"trunk"}},
	} {
		content := renderReleasePleaseCaller(s)
		wf, isRP := classifyReleasePleaseWorkflow(rpCaller, []byte(content))
		require.True(t, isRP, content)
		require.True(t, wf.Plain, "%s: %s", wf.Why, content)
		assert.Equal(t, s, wf.Settings)
	}
}

