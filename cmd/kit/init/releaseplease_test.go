const rpCaller = ".github/workflows/release-please.yml"

func rpInputs() Inputs {
	return Inputs{
		DefaultBranch:        "main",
		WithGitHubWorkflows:  true,
		WithReleasePlease:    true,
		MigrateReleasePlease: false,
	}
}

func writeRel(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o750))
	require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
}

func readRel(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	require.NoError(t, err)
	return string(b)
}

func assertAbsent(t *testing.T, root, rel string) {
	t.Helper()
	_, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel)))
	assert.True(t, os.IsNotExist(err), "%s must not exist", rel)
}

func findAction(actions []WorkflowAction, path string) (WorkflowAction, bool) {
	for _, a := range actions {
		if a.Path == path {
			return a, true
		}
	}
	return WorkflowAction{}, false
}

func mustAction(t *testing.T, actions []WorkflowAction, path string) WorkflowAction {
	t.Helper()
	a, ok := findAction(actions, path)
	require.True(t, ok, "no action for %s in %+v", path, actions)
	return a
}

// parseWorkflow decodes a rendered workflow into a generic map.
func parseWorkflow(t *testing.T, content string) map[string]any {
	t.Helper()
	var doc map[string]any
	require.NoError(t, yaml.Unmarshal([]byte(content), &doc), content)
	return doc
}

