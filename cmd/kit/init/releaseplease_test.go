// rpGit runs git in dir (GIT_* scrubbed by gitRun) with a throwaway
// identity so commits work on any machine.
func rpGit(t *testing.T, dir string, args ...string) {
	t.Helper()
	gitRun(t, "", append([]string{
		"-C", dir,
		"-c", "user.name=kit-test", "-c", "user.email=kit-test@example.com",
		"-c", "commit.gpgsign=false", "-c", "init.defaultBranch=main",
	}, args...)...)
}

// gitRepoWith creates a git repo holding files, all committed.
func gitRepoWith(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	rpGit(t, dir, "init", "-q")
	for rel, body := range files {
		writeRel(t, dir, rel, body)
	}
	rpGit(t, dir, "add", "-A")
	rpGit(t, dir, "commit", "-q", "-m", "seed")
	return dir
}

