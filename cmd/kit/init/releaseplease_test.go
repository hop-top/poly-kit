// --- idempotency -------------------------------------------------------------

func TestRenderReleasePlease_Rerun_SkipsUnchanged(t *testing.T) {
	target := t.TempDir()
	_, err := renderReleasePlease(target, rpInputs(), fixedNow())
	require.NoError(t, err)
	before := readRel(t, target, rpCaller)
	manifestBefore := readRel(t, target, manifestRelPath)

	actions, err := renderReleasePlease(target, rpInputs(), fixedNow())
	require.NoError(t, err)
	assert.Equal(t, "skip-unchanged", mustAction(t, actions, rpCaller).Action)
	assert.Equal(t, before, readRel(t, target, rpCaller))
	assert.Equal(t, manifestBefore, readRel(t, target, manifestRelPath))
	assertAbsent(t, target, rpCaller+suggestedSuffix)
}

// A managed caller carrying non-default settings must survive a re-run
// that resolves different defaults: settings are read back from the
// caller itself, not re-derived.
func TestRenderReleasePlease_Rerun_KeepsCarriedSettings(t *testing.T) {
	target := t.TempDir()
	writeRel(t, target, "release-please-config.json", `{"packages":{".":{}}}`)
	writeRel(t, target, ".release-please-manifest.json", `{}`)
	in := rpInputs()
	in.DefaultBranch = "trunk"
	_, err := renderReleasePlease(target, in, fixedNow())
	require.NoError(t, err)
	before := readRel(t, target, rpCaller)

	// Second run: different --default-branch, config moved under .github/.
	writeRel(t, target, ".github/release-please-config.json", `{"packages":{".":{}}}`)
	actions, err := renderReleasePlease(target, rpInputs(), fixedNow())
	require.NoError(t, err)
	assert.Equal(t, "skip-unchanged", mustAction(t, actions, rpCaller).Action)
	assert.Equal(t, before, readRel(t, target, rpCaller))
}

func TestRenderReleasePlease_ManagedCallerEdited_SuggestsSibling(t *testing.T) {
	target := t.TempDir()
	_, err := renderReleasePlease(target, rpInputs(), fixedNow())
	require.NoError(t, err)
	edited := readRel(t, target, rpCaller) + `
  publish:
    needs: release-please
    if: needs.release-please.outputs.releases_created == 'true'
    runs-on: ubuntu-latest
    steps:
      - run: echo publish
`
	writeRel(t, target, rpCaller, edited)

	in := rpInputs()
	in.MigrateReleasePlease = true // never applies to kit's own (edited) caller
	actions, err := renderReleasePlease(target, in, fixedNow())
	require.NoError(t, err)
	a := mustAction(t, actions, rpCaller)
	assert.Equal(t, "suggest-sibling", a.Action)
	assert.Equal(t, "user-edited", a.Reason)
	assert.Equal(t, edited, readRel(t, target, rpCaller), "user edit must survive")
}

