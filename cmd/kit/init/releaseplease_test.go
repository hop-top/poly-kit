func TestRenderReleasePleaseCaller_Defaults(t *testing.T) {
	got := renderReleasePleaseCaller(releasePleaseSettings{Branches: []string{"main"}, Dispatch: true})
	doc := parseWorkflow(t, got)

	assert.Equal(t, "release-please", doc["name"])
	on := doc["on"].(map[string]any)
	assert.Equal(t, map[string]any{"branches": []any{"main"}}, on["push"])
	assert.Contains(t, on, "workflow_dispatch")
	assert.Equal(t, map[string]any{"contents": "read"}, doc["permissions"])
	// The concurrency guard lives in the reusable workflow's job; a
	// workflow-level guard here would also cancel publish jobs chained
	// on a previous run's outputs.
	assert.NotContains(t, doc, "concurrency")

	job := doc["jobs"].(map[string]any)["release-please"].(map[string]any)
	assert.Equal(t, "hop-top/.github/.github/workflows/release-please-on-push.yml@"+workflowCallerRef, job["uses"])
	assert.NotContains(t, job, "with", "defaults must not be spelled out")
	assert.Equal(t, map[string]any{
		"RELEASE_BOT_APP_ID":      "${{ secrets.RELEASE_BOT_APP_ID }}",
		"RELEASE_BOT_PRIVATE_KEY": "${{ secrets.RELEASE_BOT_PRIVATE_KEY }}",
	}, job["secrets"])
	assert.True(t, strings.HasPrefix(got, "# Generated by `kit init`."))
}

