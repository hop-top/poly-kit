func TestAugment_ReleasePlease_MigratesAndIsIdempotent(t *testing.T) {
	tplPath := fixtureTemplate(t)
	cwd := gitRepoWith(t, map[string]string{rpCaller: legacyAppToken})
	deps, _ := fixtureDeps()
	in := baseInputs(tplPath, "demo", 1)
	in.Runtime = []string{"go"}
	in.DefaultBranch = "main"
	in.WithGitHubWorkflows = true
	in.WithReleasePlease = true
	in.MigrateReleasePlease = true

	sum, err := runAugment(t.Context(), deps, in, cwd)
	require.NoError(t, err)
	assert.Equal(t, "migrated", mustAction(t, sum.Workflows, rpCaller).Reason)
	live := readRel(t, cwd, rpCaller)

	sum, err = runAugment(t.Context(), deps, in, cwd)
	require.NoError(t, err)
	assert.Equal(t, "skip-unchanged", mustAction(t, sum.Workflows, rpCaller).Action)
	assert.Equal(t, live, readRel(t, cwd, rpCaller))
}
