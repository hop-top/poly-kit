func TestRenderReleasePlease_Fresh_WritesCallerAndTracksIt(t *testing.T) {
	target := t.TempDir()
	actions, err := renderReleasePlease(target, rpInputs(), fixedNow())
	require.NoError(t, err)

	a := mustAction(t, actions, rpCaller)
	assert.Equal(t, "write", a.Action)
	assert.Equal(t, "new", a.Reason)
	content := readRel(t, target, rpCaller)
	assert.Equal(t, renderReleasePleaseCaller(releasePleaseSettings{Branches: []string{"main"}, Dispatch: true}), content)

	m := readManifestFile(t, target)
	require.Len(t, m.Files, 1)
	assert.Equal(t, rpCaller, m.Files[0].Path)
	assert.Equal(t, sha256Hex([]byte(content)), m.Files[0].SHA256)
}

