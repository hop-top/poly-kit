// The escapers are the part of the contract a port is likeliest to get
// subtly wrong, so each rule is pinned on its own here as well as in
// the shared corpus.

func TestJSString(t *testing.T) {
	for in, want := range map[string]string{
		"plain é — ok":        `"plain é — ok"`,
		`q" bk\`:              `"q\" bk\\"`,
		"nl\n cr\r tab\t":     `"nl\n cr\r tab\t"`,
		"nul\x00 soh\x01":     `"nul\u0000 soh\u0001"`,
		"bs\b ff\f esc\x1b":   `"bs\u0008 ff\u000c esc\u001b"`,
		"del\x7f":             `"del\u007f"`,
		"ls\u2028 ps\u2029":   `"ls\u2028 ps\u2029"`,
		"nel\u0085 bom\ufeff": "\"nel\u0085 bom\ufeff\"",
		"rlo\u202e lri\u2066": "\"rlo\u202e lri\u2066\"",
		"${x} `t` </script>":  "\"${x} `t` </script>\"",
	} {
		assert.Equal(t, want, jsString(in), "%q", in)
	}
}

