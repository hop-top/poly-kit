package completionspec

import (
	"fmt"
	"regexp"
	"strings"
)

// usageRunTail is the `complete run=` command for a dynamic value. usage
// renders it as a Tera template and runs it with `sh -c`: the words
// typed so far, up to the cursor and without the binary name, become
// shell-quoted `__complete` arguments; cobra's stderr note is dropped,
// since usage passes stderr through to the terminal; and awk turns
// cobra's "value\tdescription" lines into usage's "value:description"
// (a colon in the value escaped), stopping at the ":<directive>" line
// and skipping active-help lines. It follows the binary name, written
// as a shell word.
const usageRunTail = ` __complete{% for w in words %}{% if loop.index0 > 0 and loop.index0 <= CURRENT %} {{ w | shell_quote }}{% endif %}{% endfor %} 2>/dev/null` +
	` | awk -F '\t' '/^:[0-9]+$/ { exit } /^_activeHelp_ / { next } { v = $1; gsub(/:/, "\\:", v); if (NF > 1) print v ":" $2; else print v }'`

// RenderUsage renders s as a Usage KDL spec (KDL v2).
func RenderUsage(s Spec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by `%s completion usage`. Do not edit.\n", unquote(kdlString(s.Root.Name)))
	fmt.Fprintf(&b, "name %s\n", kdlString(s.Root.Name))
	fmt.Fprintf(&b, "bin %s\n", kdlString(s.Root.Name))
	if s.Version != "" {
		fmt.Fprintf(&b, "version %s\n", kdlString(s.Version))
	}
	if s.Root.Description != "" {
		fmt.Fprintf(&b, "about %s\n", kdlString(s.Root.Description))
	}
	run := usageBin(s.Root.Name) + usageRunTail
	usageBody(&b, s.Root, 0, run)
	return b.String()
}

// usageBody writes a command's aliases, flags, args and subcommands.
func usageBody(b *strings.Builder, c Command, depth int, run string) {
	in := strings.Repeat("    ", depth)
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "%salias %s\n", in, kdlStrings(c.Aliases))
	}
	for _, f := range c.Flags {
		usageFlag(b, f, depth, run)
	}
	for _, a := range c.Args {
		name := "<" + a.Name + ">"
		if a.Optional {
			name = "[" + a.Name + "]"
		}
		fmt.Fprintf(b, "%sarg %s", in, kdlString(name))
		if a.Variadic {
			b.WriteString(" var=#true")
		}
		usageComplete(b, a.Complete, depth, run)
	}
	for _, sub := range c.Commands {
		fmt.Fprintf(b, "%scmd %s", in, kdlString(sub.Name))
		if sub.Description != "" {
			fmt.Fprintf(b, " help=%s", kdlString(sub.Description))
		}
		if sub.Hidden {
			b.WriteString(" hide=#true")
		}
		if len(sub.Aliases)+len(sub.Flags)+len(sub.Args)+len(sub.Commands) == 0 {
			b.WriteString("\n")
			continue
		}
		b.WriteString(" {\n")
		usageBody(b, sub, depth+1, run)
		fmt.Fprintf(b, "%s}\n", in)
	}
}

func usageFlag(b *strings.Builder, f Flag, depth int, run string) {
	usage := "--" + f.Name
	if f.Short != "" {
		usage = "-" + f.Short + " " + usage
	}
	if f.Arg != nil {
		usage += " <" + f.Arg.Name + ">"
	}
	fmt.Fprintf(b, "%sflag %s", strings.Repeat("    ", depth), kdlString(usage))
	if f.Description != "" {
		fmt.Fprintf(b, " help=%s", kdlString(f.Description))
	}
	for _, kv := range []struct {
		on  bool
		key string
	}{
		{f.Persistent, "global"},
		{f.Required, "required"},
		{f.Hidden, "hide"},
		{f.Repeatable && f.Arg == nil, "count"},
		{f.Repeatable && f.Arg != nil, "var"},
	} {
		if kv.on {
			fmt.Fprintf(b, " %s=#true", kv.key)
		}
	}
	if f.Arg != nil && f.Arg.Optional {
		// pflag's optional value: bare means DefaultMissing, a value
		// must be attached. usage's completer still reads the next
		// word as the value, where cobra reads a positional, so no
		// candidates are offered for it.
		fmt.Fprintf(b, " default_missing=%s require_equals=#true", kdlString(f.DefaultMissing))
		usageComplete(b, Completion{Kind: completionNoValue}, depth, run)
		return
	}
	comp := Completion{}
	if f.Arg != nil {
		comp = f.Arg.Complete
	}
	usageComplete(b, comp, depth, run)
}

// completionNoValue renders `complete type="none"`: no candidates and
// no file fallback. Internal to the Usage emitter.
const completionNoValue CompletionKind = -1

// usageComplete ends the current node: bare when there is nothing to
// complete, else with a child block holding the choices or completer.
// Choices are advisory (strict=#false): neither kit enums nor cobra
// ValidArgs reject other values.
func usageComplete(b *strings.Builder, c Completion, depth int, run string) {
	in := strings.Repeat("    ", depth+1)
	var child string
	switch c.Kind {
	case CompletionNone:
		b.WriteString("\n")
		return
	case CompletionChoices:
		child = "choices strict=#false " + kdlStrings(c.Values)
	case CompletionFile:
		typ := "file"
		if len(c.Extensions) > 0 {
			typ += ":" + strings.Join(c.Extensions, ",")
		}
		child = "complete type=" + kdlString(typ)
	case CompletionDir:
		child = `complete type="dir"`
	case completionNoValue:
		child = `complete type="none"`
	case CompletionDynamic:
		child = "complete run=" + kdlString(run) + " descriptions=#true"
	}
	fmt.Fprintf(b, " {\n%s%s\n%s}\n", in, child, strings.Repeat("    ", depth))
}

func kdlStrings(vals []string) string {
	q := make([]string, len(vals))
	for i, v := range vals {
		q[i] = kdlString(v)
	}
	return strings.Join(q, " ")
}

// kdlString quotes s as a KDL v2 quoted string. Backslash and double
// quote are escaped, as are the characters KDL v2 forbids or reads as
// a newline inside a single-line string: C0 controls, DEL, NEL, the
// Unicode line and paragraph separators, the bidi controls and the
// BOM. Everything else is written as UTF-8.
func kdlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '\b':
			b.WriteString(`\b`)
		case '\f':
			b.WriteString(`\f`)
		default:
			if kdlEscaped(r) {
				fmt.Fprintf(&b, `\u{%x}`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func kdlEscaped(r rune) bool {
	switch {
	case r < 0x20, r == 0x7f, r == 0x85,
		r == 0x200e, r == 0x200f,
		r >= 0x202a && r <= 0x202e,
		r >= 0x2066 && r <= 0x2069,
		r == 0x2028, r == 0x2029, r == 0xfeff:
		return true
	}
	return false
}

// usageBin is the binary name as it starts the run string: a shell
// word, kept out of Tera's reach in a raw block when it holds a brace.
func usageBin(name string) string {
	w := shellWord(name)
	if strings.ContainsAny(w, "{}") {
		return "{% raw %}" + w + "{% endraw %}"
	}
	return w
}

var plainShellWord = regexp.MustCompile(`^[A-Za-z0-9._+-]+$`)

// shellWord is name as one POSIX shell word: bare when it holds only
// characters no shell treats specially, else single-quoted.
func shellWord(name string) string {
	if plainShellWord.MatchString(name) {
		return name
	}
	return "'" + strings.ReplaceAll(name, "'", `'\''`) + "'"
}
