package completionspec

import (
	"fmt"
	"strings"
)

// figGenerator is the one generator every dynamic value shares: it
// runs `<bin> __complete <words typed so far>` and turns cobra's
// "value\tdescription" lines into suggestions, stopping at the
// ":<directive>" line and skipping active-help lines. %s is the binary
// name as a JS string literal.
const figGenerator = `/** @type {Fig.Generator} */
const cobraComplete = {
  script: (tokens) => [%s, "__complete", ...tokens.slice(1)],
  postProcess: (out) => {
    const suggestions = [];
    for (const line of out.split("\n")) {
      if (/^:[0-9]+$/.test(line)) break;
      if (line === "" || line.startsWith("_activeHelp_ ")) continue;
      const tab = line.indexOf("\t");
      suggestions.push(
        tab < 0
          ? { name: line }
          : { name: line.slice(0, tab), description: line.slice(tab + 1) },
      );
    }
    return suggestions;
  },
};

`

// RenderFig renders s as a Fig completion spec: an ES module whose
// default export is the Fig.Spec object. The module carries no type
// annotations, so it loads as JavaScript and compiles as TypeScript.
func RenderFig(s Spec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by `%s completion fig`. Do not edit.\n\n", s.Root.Name)
	if hasDynamic(s.Root) {
		fmt.Fprintf(&b, figGenerator, jsString(s.Root.Name))
	}
	b.WriteString("/** @type {Fig.Spec} */\nconst completionSpec = {\n")
	figCommandBody(&b, s.Root, 1, true)
	b.WriteString("};\n\nexport default completionSpec;\n")
	return b.String()
}

func hasDynamic(c Command) bool {
	for _, a := range c.Args {
		if a.Complete.Kind == CompletionDynamic {
			return true
		}
	}
	for _, f := range c.Flags {
		if f.Arg != nil && f.Arg.Complete.Kind == CompletionDynamic {
			return true
		}
	}
	for _, sub := range c.Commands {
		if hasDynamic(sub) {
			return true
		}
	}
	return false
}

func indent(depth int) string { return strings.Repeat("  ", depth) }

// figCommandBody writes the fields of a command object at depth.
func figCommandBody(b *strings.Builder, c Command, depth int, root bool) {
	in := indent(depth)
	if root {
		fmt.Fprintf(b, "%sname: %s,\n", in, jsString(c.Name))
	} else {
		fmt.Fprintf(b, "%sname: %s,\n", in, jsNames(append([]string{c.Name}, c.Aliases...)))
	}
	if c.Description != "" {
		fmt.Fprintf(b, "%sdescription: %s,\n", in, jsString(c.Description))
	}
	if c.Hidden && !root {
		fmt.Fprintf(b, "%shidden: true,\n", in)
	}
	if len(c.Commands) > 0 {
		fmt.Fprintf(b, "%ssubcommands: [\n", in)
		for _, sub := range c.Commands {
			fmt.Fprintf(b, "%s{\n", indent(depth+1))
			figCommandBody(b, sub, depth+2, false)
			fmt.Fprintf(b, "%s},\n", indent(depth+1))
		}
		fmt.Fprintf(b, "%s],\n", in)
	}
	if len(c.Flags) > 0 {
		fmt.Fprintf(b, "%soptions: [\n", in)
		for _, f := range c.Flags {
			fmt.Fprintf(b, "%s{\n", indent(depth+1))
			figOptionBody(b, f, depth+2)
			fmt.Fprintf(b, "%s},\n", indent(depth+1))
		}
		fmt.Fprintf(b, "%s],\n", in)
	}
	figArgs(b, c.Args, depth)
}

func figOptionBody(b *strings.Builder, f Flag, depth int) {
	in := indent(depth)
	names := []string{"--" + f.Name}
	if f.Short != "" {
		names = []string{"-" + f.Short, "--" + f.Name}
	}
	fmt.Fprintf(b, "%sname: %s,\n", in, jsNames(names))
	if f.Description != "" {
		fmt.Fprintf(b, "%sdescription: %s,\n", in, jsString(f.Description))
	}
	for _, kv := range []struct {
		on  bool
		key string
	}{
		{f.Hidden, "hidden"},
		{f.Persistent, "isPersistent"},
		{f.Required, "isRequired"},
		{f.Repeatable, "isRepeatable"},
	} {
		if kv.on {
			fmt.Fprintf(b, "%s%s: true,\n", in, kv.key)
		}
	}
	if f.Arg != nil {
		figArgs(b, []Arg{*f.Arg}, depth)
	}
}

// figArgs writes `args:` as one object, or an array of several.
func figArgs(b *strings.Builder, args []Arg, depth int) {
	in := indent(depth)
	switch len(args) {
	case 0:
		return
	case 1:
		fmt.Fprintf(b, "%sargs: {\n", in)
		figArgBody(b, args[0], depth+1)
		fmt.Fprintf(b, "%s},\n", in)
		return
	}
	fmt.Fprintf(b, "%sargs: [\n", in)
	for _, a := range args {
		fmt.Fprintf(b, "%s{\n", indent(depth+1))
		figArgBody(b, a, depth+2)
		fmt.Fprintf(b, "%s},\n", indent(depth+1))
	}
	fmt.Fprintf(b, "%s],\n", in)
}

func figArgBody(b *strings.Builder, a Arg, depth int) {
	in := indent(depth)
	fmt.Fprintf(b, "%sname: %s,\n", in, jsString(a.Name))
	if a.Optional {
		fmt.Fprintf(b, "%sisOptional: true,\n", in)
	}
	if a.Variadic {
		fmt.Fprintf(b, "%sisVariadic: true,\n", in)
	}
	switch a.Complete.Kind {
	case CompletionChoices:
		fmt.Fprintf(b, "%ssuggestions: %s,\n", in, jsArray(a.Complete.Values))
	case CompletionFile:
		fmt.Fprintf(b, "%stemplate: \"filepaths\",\n", in)
	case CompletionDir:
		fmt.Fprintf(b, "%stemplate: \"folders\",\n", in)
	case CompletionDynamic:
		fmt.Fprintf(b, "%sgenerators: cobraComplete,\n", in)
	}
}

// jsNames is a single name as a string, several as an array.
func jsNames(names []string) string {
	if len(names) == 1 {
		return jsString(names[0])
	}
	return jsArray(names)
}

func jsArray(vals []string) string {
	q := make([]string, len(vals))
	for i, v := range vals {
		q[i] = jsString(v)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// jsString quotes s as a double-quoted JS string literal. Backslash,
// double quote, the C0 controls, DEL and the two JS line separators
// are escaped; everything else is written as UTF-8.
func jsString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case ' ', ' ':
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04x`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
