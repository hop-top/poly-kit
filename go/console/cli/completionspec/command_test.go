// specRoot is a kit root with one leaf carrying an enum flag (static)
// and a completer-bound flag (dynamic). Validation stays on: the new
// subcommands must pass it like cobra's own completion leaves do.
func specRoot(t *testing.T) *cli.Root {
	t.Helper()
	r := cli.New(cli.Config{Name: "spectool", Version: "0.1.0", Short: "spec test tool"})
	leaf := &cobra.Command{
		Use:   "list",
		Short: "list widgets",
		Long:  "list widgets",
		RunE:  func(*cobra.Command, []string) error { return nil },
	}
	cli.SetSideEffect(leaf, cli.SideEffectRead)
	cli.SetTopLevelVerb(leaf)
	cli.SetIdempotency(leaf, cli.IdempotencyYes)
	leaf.Flags().String("status", "", "widget status")
	leaf.Flags().String("owner", "", "widget owner")
	completion.BindFlag(leaf, "owner", completion.StaticValues("ann", "bob"))
	status := &cobra.Command{
		Use:   "status",
		Short: "tool status",
		Long:  "tool status",
		RunE:  func(*cobra.Command, []string) error { return nil },
	}
	cli.SetSideEffect(status, cli.SideEffectRead)
	cli.SetTopLevelVerb(status)
	cli.SetIdempotency(status, cli.IdempotencyYes)
	r.Cmd.AddCommand(leaf, status)
	r.WithCommandFlagEnum("list", "status", "TODO", "DONE")
	return r
}

func execSpec(t *testing.T, r *cli.Root, args ...string) string {
	t.Helper()
	var stdout, stderr bytes.Buffer
	r.Cmd.SetOut(&stdout)
	r.Cmd.SetErr(&stderr)
	r.SetArgs(args)
	require.NoError(t, r.Execute(context.Background()), "stderr: %s", stderr.String())
	return stdout.String()
}

func TestCompletionFigCommand(t *testing.T) {
	out := execSpec(t, specRoot(t), "completion", "fig")
	assert.True(t, strings.HasPrefix(out, "// Generated by `spectool completion fig`. Do not edit.\n"), out)
	assert.Contains(t, out, `script: (tokens) => ["spectool", "__complete", ...tokens.slice(1)],`)
	assert.Contains(t, out, `suggestions: ["TODO", "DONE"],`, "enum values are static")
	assert.Contains(t, out, `generators: cobraComplete,`, "a bound completer calls back")
	assert.True(t, strings.HasSuffix(out, "export default completionSpec;\n"), out)
}

func TestCompletionUsageCommand(t *testing.T) {
	out := execSpec(t, specRoot(t), "completion", "usage")
	assert.True(t, strings.HasPrefix(out, "// Generated by `spectool completion usage`. Do not edit.\n"), out)
	assert.Contains(t, out, "\nbin \"spectool\"\n")
	assert.Contains(t, out, `choices strict=#false "TODO" "DONE"`)
	assert.Contains(t, out, `complete run="spectool __complete`)
}

// TestCompletionSpecCommandsSitUnderCompletion: the exports are listed
// next to the shell scripts, and cobra's own leaves keep working.
func TestCompletionSpecCommandsSitUnderCompletion(t *testing.T) {
	r := specRoot(t)
	require.NoError(t, r.Prepare())
	require.NoError(t, r.Prepare(), "registration is idempotent")
	var comp *cobra.Command
	for _, c := range r.Cmd.Commands() {
		if c.Name() == "completion" {
			comp = c
		}
	}
	require.NotNil(t, comp)
	names := map[string]int{}
	for _, c := range comp.Commands() {
		names[c.Name()]++
	}
	assert.Equal(t, 1, names["fig"])
	assert.Equal(t, 1, names["usage"])
	assert.Equal(t, 1, names["bash"])

	out := execSpec(t, specRoot(t), "completion", "bash")
	assert.Contains(t, out, "bash completion")
}

// TestCompletionSpecHidesManagementGroup: the export runs inside the
// same invocation that hid the management group from help, so the
// completion command is marked hidden, as help shows it.
func TestCompletionSpecHidesManagementGroup(t *testing.T) {
	out := execSpec(t, specRoot(t), "completion", "usage")
	assert.Contains(t, out, `cmd "completion" help="Generate the autocompletion script for the specified shell" hide=#true {`)
}

